CREATE TABLE tab_ai_conversation (
  id BIGINT NOT NULL PRIMARY KEY,
  owner_user_id BIGINT NOT NULL,
  session_id VARCHAR(64) NOT NULL,
  agno_session_id VARCHAR(64) NOT NULL,
  status VARCHAR(24) NOT NULL,
  last_message_at DATETIME(3) NULL,
  expires_at DATETIME(3) NOT NULL,
  deleted_at DATETIME(3) NULL,
  create_time DATETIME(3) NOT NULL,
  update_time DATETIME(3) NOT NULL,
  create_by BIGINT NULL,
  update_by BIGINT NULL,
  data_state CHAR(1) NOT NULL DEFAULT '0',
  UNIQUE KEY uk_ai_conversation_owner_session (owner_user_id, session_id),
  UNIQUE KEY uk_ai_conversation_agno_session (agno_session_id),
  KEY idx_ai_conversation_owner_updated (owner_user_id, update_time),
  KEY idx_ai_conversation_expiry (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE tab_ai_turn (
  id BIGINT NOT NULL PRIMARY KEY,
  owner_user_id BIGINT NOT NULL,
  conversation_id BIGINT NOT NULL,
  turn_id VARCHAR(36) NOT NULL,
  client_message_id VARCHAR(36) NOT NULL,
  request_hash CHAR(64) NOT NULL,
  agno_run_id VARCHAR(64) NULL,
  trace_id VARCHAR(36) NOT NULL,
  status VARCHAR(16) NOT NULL,
  failure_code VARCHAR(64) NULL,
  started_at DATETIME(3) NOT NULL,
  completed_at DATETIME(3) NULL,
  expires_at DATETIME(3) NOT NULL,
  create_time DATETIME(3) NOT NULL,
  update_time DATETIME(3) NOT NULL,
  create_by BIGINT NULL,
  update_by BIGINT NULL,
  data_state CHAR(1) NOT NULL DEFAULT '0',
  UNIQUE KEY uk_ai_turn_id (turn_id),
  UNIQUE KEY uk_ai_turn_idempotency (conversation_id, client_message_id),
  KEY idx_ai_turn_owner_conversation_started (owner_user_id, conversation_id, started_at),
  KEY idx_ai_turn_expiry (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE tab_ai_cleanup_task (
  id BIGINT NOT NULL PRIMARY KEY,
  owner_user_id BIGINT NOT NULL,
  conversation_id BIGINT NOT NULL,
  agno_session_id VARCHAR(64) NOT NULL,
  status VARCHAR(24) NOT NULL,
  attempt_count INT NOT NULL DEFAULT 0,
  next_attempt_at DATETIME(3) NULL,
  last_attempt_at DATETIME(3) NULL,
  completed_at DATETIME(3) NULL,
  expires_at DATETIME(3) NULL,
  last_error_code VARCHAR(64) NULL,
  create_time DATETIME(3) NOT NULL,
  update_time DATETIME(3) NOT NULL,
  create_by BIGINT NULL,
  update_by BIGINT NULL,
  data_state CHAR(1) NOT NULL DEFAULT '0',
  KEY idx_ai_cleanup_due (status, next_attempt_at),
  UNIQUE KEY uk_ai_cleanup_conversation (conversation_id),
  KEY idx_ai_cleanup_expiry (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
