CREATE TABLE tab_insurance_term_source (
  id BIGINT NOT NULL PRIMARY KEY,
  insurance_id BIGINT NOT NULL,
  profile_version_id BIGINT NOT NULL,
  product_version INT NOT NULL,
  source_type VARCHAR(32) NOT NULL,
  title VARCHAR(255) NOT NULL,
  source_uri VARCHAR(1024) NULL,
  original_file_name VARCHAR(255) NOT NULL,
  content_type VARCHAR(128) NOT NULL,
  file_size BIGINT NOT NULL,
  sha256 CHAR(64) NOT NULL,
  storage_provider VARCHAR(32) NOT NULL,
  bucket_name VARCHAR(128) NOT NULL,
  object_key VARCHAR(512) NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'DRAFT',
  effective_from DATE NULL,
  effective_to DATE NULL,
  uploaded_by BIGINT NOT NULL,
  create_time DATETIME(3) NOT NULL,
  update_time DATETIME(3) NOT NULL,
  create_by BIGINT NULL,
  update_by BIGINT NULL,
  data_state CHAR(1) NOT NULL DEFAULT '0',
  KEY idx_insurance_term_source_product_version (insurance_id, profile_version_id, status),
  KEY idx_insurance_term_source_sha256 (sha256)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
